def country_code_field():
    return forms.ChoiceField(
        choices=COUNTRY_CALLING_CODES,
        initial="255",
        required=False,
        widget=forms.Select(
            attrs={
                "data-searchable": "true",
                "data-search-placeholder": "Search country or code",
            }
        ),
    )


def split_phone_number(value):
    digits = re.sub(r"\D", "", value or "")
    for code, _label in sorted(
        COUNTRY_CALLING_CODES,
        key=lambda item: len(item[0]),
        reverse=True,
    ):
        if digits.startswith(code) and len(digits) > len(code):
            return code, digits[len(code) :]
    return "255", digits.removeprefix("0")


def normalize_phone_number(country_code, local_number):
    code = re.sub(r"\D", "", country_code or "255")
    local = re.sub(r"\D", "", local_number or "").lstrip("0")
    if local.startswith(code) and len(local) - len(code) >= 7:
        local = local[len(code) :]
    if not code or not local:
        raise forms.ValidationError("Enter a valid phone number.")

    combined = f"{code}{local}"
    if len(combined) < 8 or len(combined) > 15:
        raise forms.ValidationError(
            "Enter a valid international phone number with 8 to 15 digits."
        )
    return f"+{combined}"
